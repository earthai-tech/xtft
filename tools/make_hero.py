"""Write the animated forecast drawing of the documentation home page.

The drawing is an inline SVG fragment (``docs/_static/hero.html``)
so that it takes the colours of the page theme (light or dark)
from CSS variables; the animation itself is in
``docs/_static/custom.css``. The series is synthetic and fixed by
a seed, so the output is reproducible:

    python tools/make_hero.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parents[1] / "docs/_static/hero.html"

W, H = 640, 380  # view box
X0, X_ORIGIN, X1 = 16, 400, 624  # history start, origin, horizon end
Y_TOP, Y_BOT = 46, 350  # plotting band
N_PAST, N_FUT = 72, 36  # steps
Z = {0.5: 0.674, 0.8: 1.2816, 0.9: 1.6449}  # normal quantiles
NOISE = 0.13  # standard deviation of the observation noise


def signal(t: np.ndarray) -> np.ndarray:
    """Seasonal pattern with a slow upward drift of the level."""
    return 0.01 * t + np.sin(2 * np.pi * t / 30)


def series(seed: int = 3) -> tuple[np.ndarray, np.ndarray]:
    """History and future of the series, with noise."""
    rng = np.random.default_rng(seed)
    t = np.arange(N_PAST + N_FUT)
    y = signal(t) + NOISE * rng.normal(size=t.size)
    return y[:N_PAST], y[N_PAST:]


def main() -> None:
    past, fut = series()
    t = np.arange(N_PAST + N_FUT)
    mean = signal(t[N_PAST:])
    h = np.arange(1, N_FUT + 1)
    # The spread grows with the horizon, as for a random-walk error.
    sd = NOISE + 0.07 * np.sqrt(h)
    lo_all = mean - Z[0.9] * sd
    hi_all = mean + Z[0.9] * sd
    vmin = min(past.min(), lo_all.min()) - 0.1
    vmax = max(past.max(), hi_all.max()) + 0.1

    def sx(i: np.ndarray, future: bool) -> np.ndarray:
        if future:
            return X_ORIGIN + (X1 - X_ORIGIN) * i / N_FUT
        return X0 + (X_ORIGIN - X0) * i / (N_PAST - 1)

    def sy(v: np.ndarray) -> np.ndarray:
        return Y_BOT - (Y_BOT - Y_TOP) * (v - vmin) / (vmax - vmin)

    def pts(xs, ys) -> str:
        return " ".join(
            f"{x:.1f},{y:.1f}" for x, y in zip(xs, ys, strict=True)
        )

    xp, yp = sx(np.arange(N_PAST), False), sy(past)
    xf = sx(h, True)
    # Every band starts at the last observation, the origin.
    ox, oy = X_ORIGIN, float(sy(past[-1:])[0])
    bands = []
    for cov, cls in ((0.9, "b90"), (0.8, "b80"), (0.5, "b50")):
        lo, hi = sy(mean - Z[cov] * sd), sy(mean + Z[cov] * sd)
        poly = (
            f"{ox:.1f},{oy:.1f} "
            + pts(xf, hi)
            + " "
            + pts(xf[::-1], lo[::-1])
        )
        bands.append(
            f'<polygon class="xh-band xh-{cls}" points="{poly}"/>'
        )
    median = f"M{ox:.1f},{oy:.1f} L" + pts(xf, sy(mean))
    history = "M" + pts(xp, yp).replace(" ", " L")
    dots = "\n".join(
        f'    <circle class="xh-obs" cx="{x:.1f}" cy="{y:.1f}" r="3"'
        f' style="animation-delay:{0.06 * k:.2f}s"/>'
        for k, (x, y) in enumerate(zip(xf, sy(fut), strict=True))
        if k % 2 == 0
    )
    grid = "\n".join(
        f'    <line class="xh-grid" x1="{X0}" x2="{X1}" '
        f'y1="{y:.0f}" y2="{y:.0f}"/>'
        for y in np.linspace(Y_TOP, Y_BOT, 5)
    )
    y_lab = float(sy(mean[-1] + Z[0.9] * sd[-1])) - 8
    svg = f"""<svg class="xtft-hero-art" viewBox="0 0 {W} {H}"
     xmlns="http://www.w3.org/2000/svg" role="img"
     aria-labelledby="xh-title xh-desc">
  <title id="xh-title">A probabilistic forecast</title>
  <desc id="xh-desc">An observed series is drawn up to the forecast
  origin; a fan of 50, 80 and 90 percent intervals then opens over
  the horizon, and the later observations fall mostly inside it.</desc>
  <!-- Generated by tools/make_hero.py; do not edit by hand. -->
  <g>
{grid}
  </g>
  <g class="xh-fan">
    {bands[0]}
    {bands[1]}
    {bands[2]}
    <path class="xh-median" d="{median}"/>
  </g>
  <path class="xh-history" d="{history}" pathLength="1"/>
  <line class="xh-origin" x1="{ox:.1f}" x2="{ox:.1f}"
        y1="{Y_TOP - 18}" y2="{Y_BOT + 10}"/>
  <text class="xh-label" x="{ox - 6:.1f}" y="{Y_TOP - 22}"
        text-anchor="end">history</text>
  <text class="xh-label" x="{ox + 6:.1f}"
        y="{Y_TOP - 22}">forecast</text>
  <g class="xh-legend">
    <text class="xh-label xh-small" x="{X1}" y="{y_lab:.1f}"
          text-anchor="end">90% band</text>
  </g>
  <g>
{dots}
  </g>
  <circle class="xh-now" cx="{ox:.1f}" cy="{oy:.1f}" r="4.5"/>
</svg>
"""
    OUT.write_text(svg, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
